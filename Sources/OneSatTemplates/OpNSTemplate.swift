/// The state an OpNS node carries in its OP_RETURN trailer: `OpNSData` in `@1sat/templates`.
public struct OpNSData: Equatable, Sendable {
    /// Claimed-character bitfield (little-endian).
    public let claimed: [UInt8]
    /// The name mined so far.
    public let domain: String
    /// Proof-of-work root: the sha256d hash the node was mined to.
    public let pow: [UInt8]

    public init(claimed: [UInt8], domain: String, pow: [UInt8]) {
        self.claimed = claimed
        self.domain = domain
        self.pow = pow
    }
}

