    /// `OpNS.lock(claimed, domain, pow)`: the covenant followed by the stateful trailer.
    public static func lock(claimed: [UInt8], domain: String, pow: [UInt8]) throws -> Script {
        var state = try TemplateScript.empty()
        try TemplateScript.append(.return, to: &state)
        try TemplateScript.append(.false, to: &state)
        try TemplateScript.appendPush(genesis, to: &state)
        try TemplateScript.appendPush(claimed, to: &state)
        try TemplateScript.appendPush(Array(domain.utf8), to: &state)
        try TemplateScript.appendPush(pow, to: &state)
        let stateBytes = state.bytes
        let length = UInt32(stateBytes.count - 1)
        let trailer: [UInt8] = (0..<4).map { UInt8(truncatingIfNeeded: length >> ($0 * 8)) } + [0]
        return try TemplateScript.concatenating([contract, stateBytes, trailer])
    }

    /// `OpNS.decode(script)`: the node's state, or nil when the script does not start with the
    /// covenant or its first state push does not start with the genesis outpoint.
    ///
    /// The state is read the way `@bsv/sdk` `Script.fromBinary` reads it, past the two bytes
    /// after the covenant (not checked, as in TS): a push cut short yields the bytes that remain,
    /// and the domain is decoded as `TextDecoder` decodes UTF-8 (a leading BOM dropped, invalid
    /// bytes replaced).
    public static func decode(_ script: Script) -> OpNSData? {
        let bytes = script.bytes
        guard bytes.count >= contract.count, bytes.starts(with: contract) else { return nil }
        let stateStart = min(contract.count + 2, bytes.count)
        let chunks = leadingChunkData(bytes[stateStart...], count: 4)
        guard let genesisData = chunks.first ?? nil,
              genesisData.count >= genesis.count,
              genesisData.starts(with: genesis)
        else { return nil }
        let chunk = { (index: Int) -> [UInt8] in
            index < chunks.count ? chunks[index] ?? [] : []
        }
        var domain = chunk(2)
        if domain.starts(with: [0xef, 0xbb, 0xbf]) { domain.removeFirst(3) }
        return OpNSData(
            claimed: chunk(1),
            domain: String(decoding: domain, as: UTF8.self),
            pow: chunk(3)
        )
    }

    /// `OpNS.buildInscription(domain, ownerScript)`: the name's 1Sat inscription locked to
    /// `ownerScript`, `OP_RETURN <bitcom> <genesis>` after the envelope.
    public static func buildInscription(domain: String, ownerScript: Script) throws -> Script {
        var script = try TemplateScript.script(bytes: ownerScript.bytes)
        try TemplateScript.append(.false, to: &script)
        try TemplateScript.append(.if, to: &script)
        try TemplateScript.appendPush(Array("ord".utf8), to: &script)
        try TemplateScript.append(.one, to: &script)
        try TemplateScript.appendPush(Array(contentType.utf8), to: &script)
        try TemplateScript.append(.zero, to: &script)
        try TemplateScript.appendPush(Array(domain.utf8), to: &script)
        try TemplateScript.append(.endIf, to: &script)
        try TemplateScript.append(.return, to: &script)
        try TemplateScript.appendPush(Array(bitcom.utf8), to: &script)
        try TemplateScript.appendPush(genesis, to: &script)
        return script
    }

    /// The data of the first `count` chunks as `@bsv/sdk` `Script.parseChunks` reads them: nil
    /// for an opcode, a short push's remaining bytes, and everything after a top-level
    /// `OP_RETURN` as that chunk's data. It never fails.
    static func leadingChunkData(_ bytes: ArraySlice<UInt8>, count: Int) -> [[UInt8]?] {
        var chunks: [[UInt8]?] = []
        var position = bytes.startIndex
        let end = bytes.endIndex
        var conditionalDepth = 0
        func byte(_ index: Int) -> Int { index < end ? Int(bytes[index]) : 0 }
        func take(_ length: Int) -> [UInt8] {
            let stop = min(position + length, end)
            defer { position = stop }
            return Array(bytes[position..<stop])
        }
        while position < end, chunks.count < count {
            let op = Int(bytes[position])
            position += 1
            if op == Int(Opcode.return.rawValue), conditionalDepth == 0 {
                chunks.append(take(end - position))
                break
            }
            switch op {
            case 0x63, 0x64, 0x65, 0x66: conditionalDepth += 1
            case 0x68: conditionalDepth -= 1
            default: break
            }
            switch op {
            case 0x01..<0x4c:
                chunks.append(take(op))
            case 0x4c:
                let length = byte(position)
                position = min(position + 1, end)
                chunks.append(take(length))
            case 0x4d:
                let length = byte(position) | byte(position + 1) << 8
                position = min(position + 2, end)
                chunks.append(take(length))
            case 0x4e:
                let length = byte(position) | byte(position + 1) << 8
                    | byte(position + 2) << 16 | byte(position + 3) << 24
                position = min(position + 4, end)
                chunks.append(take(length))
            default:
                chunks.append(nil)
            }
        }
        return chunks
    }
